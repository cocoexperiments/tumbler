"""Generates the Tumbler logo as SVG + Android vector drawables from one set of parameters.
usage: gen_logo.py <repo_root>"""
import os, sys

PALM, CREAM, INK = "#8FD6B0", "#ECEAE0", "#0F1210"

# Geometry in the 108-unit adaptive-icon canvas (content stays inside the 66-unit safe zone).
BODY = dict(x=30, y=50, w=48, h=36, r=7)
SHACKLE = dict(cx=54, left=40, right=68, leg_top=38, leg_bottom=50, width=6)  # arc radius = 14
DOT_R, GRID_X, GRID_Y = 2.8, (44, 54, 64), (58, 68, 78)

def circle(cx, cy, r, dx=0, dy=0):
    cx, cy = cx - dx, cy - dy
    return f"M{cx:g},{cy:g}m-{r:g},0a{r:g},{r:g} 0 1,0 {2*r:g},0a{r:g},{r:g} 0 1,0 -{2*r:g},0"

def body_path(dx=0, dy=0):
    b = BODY; x, y, w, h, r = b["x"] - dx, b["y"] - dy, b["w"], b["h"], b["r"]
    p = (f"M{x+r:g},{y:g}h{w-2*r:g}a{r},{r} 0 0,1 {r},{r}v{h-2*r:g}a{r},{r} 0 0,1 -{r},{r}"
         f"h-{w-2*r:g}a{r},{r} 0 0,1 -{r},-{r}v-{h-2*r:g}a{r},{r} 0 0,1 {r},-{r}z")
    holes = " ".join(circle(gx, gy, DOT_R, dx, dy) for gy in GRID_Y for gx in GRID_X)
    return p + " " + holes

def shackle_path(dx=0, dy=0):
    s = SHACKLE; r = (s["right"] - s["left"]) / 2
    return (f"M{s['left']-dx:g},{s['leg_bottom']-dy:g}V{s['leg_top']-dy:g}"
            f"a{r:g},{r:g} 0 0,1 {2*r:g},0V{s['leg_bottom']-dy:g}")

def vector(w, h, vw, vh, body_col, shackle_col, dx=0, dy=0):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by logo/gen_logo.py. Padlock whose body is a 3x3 keypad of punched-out dots. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{w}dp"
    android:height="{h}dp"
    android:viewportWidth="{vw}"
    android:viewportHeight="{vh}">
    <path
        android:fillColor="#00000000"
        android:pathData="{shackle_path(dx, dy)}"
        android:strokeColor="{shackle_col}"
        android:strokeLineCap="round"
        android:strokeWidth="{SHACKLE['width']}" />
    <path
        android:fillColor="{body_col}"
        android:fillType="evenOdd"
        android:pathData="{body_path(dx, dy)}" />
</vector>
'''

def svg(bg=True):
    bgrect = f'<rect width="108" height="108" rx="24" fill="{INK}"/>' if bg else ""
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">{bgrect}
<path fill="none" stroke="{CREAM}" stroke-width="{SHACKLE['width']}" stroke-linecap="round" d="{shackle_path()}"/>
<path fill="{PALM}" fill-rule="evenodd" d="{body_path()}"/>
</svg>
'''

if __name__ == "__main__":
    root = sys.argv[1]
    res = os.path.join(root, "app/src/main/res/drawable")
    os.makedirs(res, exist_ok=True); os.makedirs(os.path.join(root, "docs"), exist_ok=True)
    open(f"{res}/ic_launcher_foreground.xml", "w").write(vector(108, 108, 108, 108, PALM, CREAM))
    open(f"{res}/ic_launcher_monochrome.xml", "w").write(vector(108, 108, 108, 108, "#FF000000", "#FF000000"))
    # In-app logo: cropped to the mark (x 24..84, y 18..90 => 60x72 canvas).
    open(f"{res}/ic_logo.xml", "w").write(vector(60, 72, 60, 72, PALM, CREAM, dx=24, dy=18))
    open(os.path.join(root, "docs/logo.svg"), "w").write(svg(True))
